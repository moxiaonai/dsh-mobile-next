import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { irohPairingContent, pairingRequestIsCurrent, validateIrohConfig } from '../src/client.js'

// Pure client helpers + source contract regressions. No simulated browser renderer,
// network listeners, native processes or actual remote tunnels are needed.
const source = readFileSync(new URL('../src/client.tsx', import.meta.url), 'utf8')

describe('iroh client configuration', () => {
  it('uses only iroh, an absolute component path and the dedicated local port', () => {
    expect(validateIrohConfig(' /opt/iroh/host ', '3445')).toEqual({
      provider: 'iroh', irohPath: '/opt/iroh/host', localPort: 3445,
    })
    expect(validateIrohConfig('C:\\iroh\\host.exe', '3446').irohPath).toBe('C:\\iroh\\host.exe')
    expect(validateIrohConfig('', '3445')).toEqual({ provider: 'iroh', localPort: 3445 })
    expect(() => validateIrohConfig('iroh-host', '3445')).toThrow('绝对路径')
    expect(() => validateIrohConfig('./host', '3445')).toThrow('绝对路径')
    expect(validateIrohConfig('/opt/iroh/host', '1024').localPort).toBe(1024)
    expect(validateIrohConfig('/opt/iroh/host', '65535').localPort).toBe(65535)
    for (const port of ['0', '1', '1023', '65536', '3445.2', '', 'invalid']) {
      expect(() => validateIrohConfig('/opt/iroh/host', port)).toThrow('端口')
    }
  })

  it('copies descriptor JSON unchanged, even without a QR image', () => {
    const descriptor = { version: 1, type: 'iroh', endpointId: 'endpoint', gatewayToken: 'token' }
    const qrPayload = JSON.stringify(descriptor)
    expect(irohPairingContent({ descriptor, qrPayload })).toBe(qrPayload)
    expect(() => irohPairingContent({ descriptor })).toThrow('描述符')
    expect(() => irohPairingContent({ descriptor, qrPayload: 'https://endpoint.iroh.localhost' })).toThrow()
    expect(() => irohPairingContent({ descriptor, qrPayload: 'null' })).toThrow('格式无效')
  })
})

describe('channel isolation and client contracts', () => {
  it('rejects responses from another channel and from an earlier channel visit', () => {
    const request = { channel: 'lan' as const, epoch: 1 }
    expect(pairingRequestIsCurrent(request, { channel: 'lan', epoch: 1 })).toBe(true)
    expect(pairingRequestIsCurrent(request, { channel: 'remote', epoch: 1 })).toBe(false)
    expect(pairingRequestIsCurrent(request, { channel: 'lan', epoch: 3 })).toBe(false)
  })

  it('keeps LAN pairing and gives remote startup its own extended timeout', () => {
    expect(source).toContain("request.channel === 'remote' ? '/remote/pairing' : '/pairing'")
    expect(source).toContain("channel !== 'lan' || autoGenerated.current[channel]")
    expect(source).toContain('const REMOTE_START_TIMEOUT_MS = 75_000')
    expect(source).toContain("requestChannel === 'remote' ? REMOTE_START_TIMEOUT_MS : REQUEST_TIMEOUT_MS")
    expect(source).toContain('if (!pairingRequestIsCurrent(request, pairingContext.current)) return')
  })

  it('uses channel-aware device identities and revoke bodies', () => {
    expect(source).toContain('JSON.stringify({ deviceId, channel: deviceChannel })')
    expect(source).toContain('key={`${device.channel}:${device.deviceId}`}')
    expect(source).toContain('void revoke(device.deviceId, device.channel)')
    expect(source).toContain("api('/devices/revoke-all'")
  })

  it('matches backend port limits and does not claim a failed clipboard copy succeeded', () => {
    expect(source).toContain('type="number" min={1024} max={65535}')
    expect(source).toContain('本地端口必须是 1024–65535 的整数')
    expect(source).toContain("if (!document.execCommand('copy')) throw new Error")
    expect(source).toContain('area.remove()')
  })

  it('keeps narrow-screen header actions reachable and names the fallback without a LAN-only label', () => {
    expect(source).toContain('display: flex; flex-wrap: wrap; align-items: center; justify-content: space-between')
    expect(source).toContain('.dshmn-headActions { display: flex; flex-wrap: wrap;')
    expect(source).toContain('flex: 0 1 auto; max-width: 100%; margin-left: auto;')
    expect(source).not.toContain('{PANEL_LABEL}（局域网）')
  })

  it('does not advertise browser connectivity or silently enable missing components', () => {
    expect(source).not.toMatch(/cloudflared|publicOrigin|relayUrl/u)
    expect(source).toContain('本地端点已就绪 · 手机跨网尚未验证')
    expect(source).toContain('不可在浏览器打开')
    expect(source).toContain('!status.irohPath?.trim()')
    expect(source).toContain('复制 iroh 配对描述符')
    expect(source).toContain('if (status === undefined || dirty) return')
    expect(source).toContain('hidden={channel !== \'remote\'}')
    expect(source).toContain("previousStatus.current?.remote?.endpointId !== nextStatus.remote?.endpointId")
    expect(source).not.toContain('.dshmn-rail { display: none; }')
  })
})
